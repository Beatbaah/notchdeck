import AppKit

/// Keeps the last 40 copied text snippets in memory only (nothing is written to disk).
final class ClipboardModel: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    /// macOS is refusing NotchDeck's reads (see `isBlocked`).
    @Published private(set) var blocked = false

    private let limit = 40
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    init() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChangeCount else { return }
        lastChangeCount = board.changeCount

        if #available(macOS 15.4, *) {
            let isBlocked = Self.isBlocked(board.accessBehavior)
            if isBlocked != blocked { blocked = isBlocked }
            if isBlocked { return }
        }
        let types = Set(board.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = board.string(forType: .string),
              Self.shouldKeep(text: text, types: types) else { return }

        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        lastChangeCount = board.changeCount
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text), at: 0)
    }

    func remove(_ text: String) {
        items.removeAll { $0.text == text }
    }

    func clear() {
        items.removeAll()
    }
}

extension ClipboardModel {
    /// Longer copies (a whole log file, say) aren't kept: they'd slow the list for little use.
    static let maxLength = 1_000_000

    // Password managers mark secrets with these types; they are never recorded.
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static func shouldKeep(text: String, types: Set<NSPasteboard.PasteboardType>) -> Bool {
        types.isDisjoint(with: skippedTypes)
            && text.utf16.count <= maxLength
            && !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// The user chose "Don't Allow" for NotchDeck in macOS's paste privacy settings.
    @available(macOS 15.4, *)
    static func isBlocked(_ behavior: NSPasteboard.AccessBehavior) -> Bool {
        behavior == .alwaysDeny
    }
}

/// One copied snippet, with a short one-line preview worked out once.
struct ClipItem: Identifiable, Equatable {
    static let previewLength = 200

    let id = UUID()
    let text: String
    let preview: String

    init(text: String) {
        self.text = text
        let head = text.prefix(Self.previewLength * 2)
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
            .trimmingCharacters(in: .whitespaces)
        preview = String(head.prefix(Self.previewLength))
    }

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.text == b.text }
}
